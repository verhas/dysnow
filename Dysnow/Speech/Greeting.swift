    static func text(languageID: String, name: String) -> String {
        switch languageID == "wen" ? languageID : String(languageID.prefix(2)) {
        case "ar": "مرحبا، أنا \(name). هكذا يبدو صوتي."
        case "ca": "Hola, sóc \(name). Així sona la meva veu."
        case "cs": "Ahoj, jsem \(name). Takhle zní můj hlas."
        case "cy": "Helo, \(name) ydw i. Dyma sut mae fy llais yn swnio."
        case "da": "Hej, jeg er \(name). Sådan lyder min stemme."
        case "de": "Hallo, ich bin \(name). So klingt meine Stimme."
        case "el": "Γεια σας, με λένε \(name). Έτσι ακούγεται η φωνή μου."
        case "eu": "Kaixo, \(name) naiz. Horrela entzuten da nire ahotsa."
        case "fa": "سلام، من \(name) هستم. صدای من این‌طور است."
        case "fi": "Hei, olen \(name). Tältä ääneni kuulostaa."
        case "id": "Halo, saya \(name). Beginilah suara saya."
        case "is": "Halló, ég heiti \(name). Svona hljómar röddin mín."
        case "ka": "გამარჯობა, მე ვარ \(name). ასე ჟღერს ჩემი ხმა."
        case "kk": "Сәлем, мен \(name). Менің дауысым осылай естіледі."
        case "ku": "Silav, ez \(name) im. Dengê min wiha ye."
        case "lb": "Moien, ech sinn \(name). Esou kléngt meng Stëmm."
        case "lv": "Sveiki, es esmu \(name). Lūk, kā skan mana balss."
        case "ml": "നമസ്കാരം, ഞാൻ \(name) ആണ്. എന്റെ ശബ്ദം ഇങ്ങനെയാണ്."
        case "ne": "नमस्ते, म \(name) हुँ। मेरो आवाज यस्तो सुनिन्छ।"
        case "nl": "Hallo, ik ben \(name). Zo klinkt mijn stem."
        case "no": "Hei, jeg er \(name). Slik høres stemmen min ut."
        case "pl": "Cześć, jestem \(name). Tak brzmi mój głos."
        case "ro": "Bună, sunt \(name). Așa sună vocea mea."
        case "sk": "Ahoj, som \(name). Takto znie môj hlas."
        case "sl": "Živjo, sem \(name). Tako zveni moj glas."
        case "sq": "Përshëndetje, unë jam \(name). Kështu tingëllon zëri im."
        case "sv": "Hej, jag heter \(name). Så här låter min röst."
        case "sw": "Habari, mimi ni \(name). Hivi ndivyo sauti yangu inavyosikika."
        case "tr": "Merhaba, ben \(name). Sesim böyle duyuluyor."
        case "uk": "Привіт, я \(name). Ось так звучить мій голос."
        case "ur": "ہیلو، میں \(name) ہوں۔ میری آواز ایسی ہے۔"
        case "vi": "Xin chào, tôi là \(name). Đây là giọng nói của tôi."
        case "wen": "Dobry dźeń, ja sym \(name)."
        case "es": "Hola, soy \(name). Así es como sueno."
        case "fr": "Bonjour, je suis \(name). Voici ma voix."
        case "hi": "नमस्ते, मैं \(name) हूँ। मेरी आवाज़ ऐसी है।"
        case "hu": "Szia, \(name) vagyok. Így szól a hangom."
        case "it": "Ciao, sono \(name). Ecco come suona la mia voce."
        case "ko": "안녕하세요, 저는 \(name)입니다. 제 목소리는 이렇습니다."
        case "ja": "こんにちは、\(name)です。私の声はこんな感じです。"
        case "pt": "Olá, eu sou \(name). Esta é a minha voz."
        case "ru": "Привет, я \(name). Вот так звучит мой голос."
        case "zh": "你好，我是\(name)。这就是我的声音。"
        default: "Hi, I am \(name). This is how I sound."
        }
    }
}
